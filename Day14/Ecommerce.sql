CREATE DATABASE IF NOT EXISTS RETAIL_DB;
SHOW DATABASES LIKE 'RETAIL_DB';



USE DATABASE RETAIL_DB;
CREATE SCHEMA IF NOT EXISTS RAW;
USE SCHEMA RETAIL_DB.RAW;
SHOW SCHEMAS IN DATABASE RETAIL_DB;


CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

    USE WAREHOUSE RETAIL_WH;
    SHOW WAREHOUSES LIKE 'RETAIL_WH';
    SELECT CURRENT_WAREHOUSE();

    CREATE TABLE IF NOT EXISTS SALES (
    ORDER_ID NUMBER,
    PRODUCT VARCHAR,
    QUANTITY NUMBER,
    UNIT_PRICE NUMBER(10,2),
    CITY VARCHAR
);


USE DATABASE RETAIL_DB;

USE SCHEMA RAW;

USE WAREHOUSE RETAIL_WH;

CREATE TABLE RETAIL_DB.RAW.ECOMMERCE (
    INVOICENO NUMBER(10,0),
    STOCKCODE VARCHAR(20),
    DESCRIPTION VARCHAR(500),
    QUANTITY NUMBER(10,0),
    INVOICEDATE TIMESTAMP_NTZ,
    UNITPRICE NUMBER(10,2),
    CUSTOMERID NUMBER(10,0),
    COUNTRY VARCHAR(100),
    REVENUE NUMBER(12,2)
);

SHOW TABLES LIKE 'ECOMMERCE'
IN SCHEMA RETAIL_DB.RAW;
DESCRIBE TABLE RETAIL_DB.RAW.ECOMMERCE;

CREATE FILE FORMAT RETAIL_DB.RAW.ECOMMERCE_CSV_FORMAT
    TYPE = CSV
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('NULL', 'null')
    EMPTY_FIELD_AS_NULL = TRUE;

SHOW FILE FORMATS IN SCHEMA RETAIL_DB.RAW;

SELECT
    CURRENT_DATABASE(),
    CURRENT_SCHEMA(),
    CURRENT_ROLE();

CREATE STAGE IF NOT EXISTS RETAIL_DB.RAW.ECOMMERCE_STAGE
    FILE_FORMAT = RETAIL_DB.RAW.ECOMMERCE_CSV_FORMAT;

SHOW STAGES IN SCHEMA RETAIL_DB.RAW;

LIST @RETAIL_DB.RAW.ECOMMERCE_STAGE;

COPY INTO RETAIL_DB.RAW.ECOMMERCE
FROM @RETAIL_DB.RAW.ECOMMERCE_STAGE
FILE_FORMAT = (
    FORMAT_NAME = 'RETAIL_DB.RAW.ECOMMERCE_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_RECORDS
FROM RETAIL_DB.RAW.ECOMMERCE;

SELECT *
FROM RETAIL_DB.RAW.ECOMMERCE
ORDER BY INVOICENO;


SELECT
    INVOICENO,
    STOCKCODE,
    COUNT(*) AS RECORD_COUNT
FROM RETAIL_DB.RAW.ECOMMERCE
GROUP BY INVOICENO, STOCKCODE
HAVING COUNT(*) > 1;


SELECT
    SUM(REVENUE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.ECOMMERCE;

SELECT
    SUM(REVENUE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.ECOMMERCE;

SELECT
    COUNTRY,
    SUM(REVENUE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.ECOMMERCE
GROUP BY COUNTRY
ORDER BY TOTAL_REVENUE DESC;

SELECT
    DESCRIPTION,
    SUM(REVENUE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.ECOMMERCE
GROUP BY DESCRIPTION
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;

SELECT
    SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM RETAIL_DB.RAW.ECOMMERCE;

SELECT
    DATE_TRUNC('MONTH', INVOICEDATE) AS SALES_MONTH,
    SUM(REVENUE) AS TOTAL_REVENUE
FROM RETAIL_DB.RAW.ECOMMERCE
GROUP BY SALES_MONTH
ORDER BY SALES_MONTH;

ALTER WAREHOUSE RETAIL_WH SUSPEND;

DROP TABLE IF EXISTS RETAIL_DB.RAW.ECOMMERCE;

DROP STAGE IF EXISTS RETAIL_DB.RAW.ECOMMERCE_STAGE;

DROP FILE FORMAT IF EXISTS RETAIL_DB.RAW.ECOMMERCE_CSV_FORMAT;

SELECT
    CURRENT_ROLE() AS CURRENT_ROLE,
    CURRENT_DATABASE() AS CURRENT_DATABASE,
    CURRENT_SCHEMA() AS CURRENT_SCHEMA,
    CURRENT_WAREHOUSE() AS CURRENT_WAREHOUSE;
    
SHOW WAREHOUSES LIKE 'RETAIL_WH';

