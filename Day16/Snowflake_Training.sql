CREATE WAREHOUSE IF NOT EXISTS RENEWABLE_ENERGY_WH
WITH
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

    USE WAREHOUSE RENEWABLE_ENERGY_WH;

CREATE DATABASE IF NOT EXISTS RENEWABLE_ENERGY_DB;

CREATE SCHEMA IF NOT EXISTS
    RENEWABLE_ENERGY_DB.SALES_SCHEMA;

USE DATABASE RENEWABLE_ENERGY_DB;

USE SCHEMA SALES_SCHEMA;


CREATE OR REPLACE FILE FORMAT
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.RENEWABLE_CSV_FORMAT

TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('NULL', 'null')
DATE_FORMAT = 'YYYY-MM-DD'
TRIM_SPACE = TRUE;

SHOW FILE FORMATS IN SCHEMA
    RENEWABLE_ENERGY_DB.SALES_SCHEMA;

CREATE OR REPLACE STAGE
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.RENEWABLE_SALES_STAGE

FILE_FORMAT =
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.RENEWABLE_CSV_FORMAT;

SHOW STAGES IN SCHEMA
    RENEWABLE_ENERGY_DB.SALES_SCHEMA;

LIST @RENEWABLE_ENERGY_DB.SALES_SCHEMA.RENEWABLE_SALES_STAGE;

CREATE OR REPLACE TABLE
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW (
        ORDER_ID NUMBER,
        ORDER_DATE DATE,
        CUSTOMER_NAME VARCHAR(100),
        CUSTOMER_CITY VARCHAR(100),
        CUSTOMER_TYPE VARCHAR(50),
        PRODUCT_NAME VARCHAR(100),
        QUANTITY NUMBER,
        UNIT_PRICE_INR NUMBER(12,2),
        ORDER_LOCATION VARCHAR(100),
        PAYMENT_METHOD VARCHAR(50),
        SALES_CHANNEL VARCHAR(50)
    );

DESC TABLE
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW;

 COPY INTO
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW

FROM
    @RENEWABLE_ENERGY_DB.SALES_SCHEMA.RENEWABLE_SALES_STAGE

FILES = (
    'renewable_energy_sales_with_missing_values.csv'
)

FILE_FORMAT = (
    FORMAT_NAME =
    'RENEWABLE_ENERGY_DB.SALES_SCHEMA.RENEWABLE_CSV_FORMAT'
)

ON_ERROR = 'ABORT_STATEMENT';


SELECT *
FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW;


SELECT
    COUNT(*) AS TOTAL_RECORDS,

    COUNT_IF(CUSTOMER_NAME IS NULL) AS MISSING_CUSTOMER_NAME,
    COUNT_IF(CUSTOMER_CITY IS NULL) AS MISSING_CUSTOMER_CITY,
    COUNT_IF(CUSTOMER_TYPE IS NULL) AS MISSING_CUSTOMER_TYPE,
    COUNT_IF(PRODUCT_NAME IS NULL) AS MISSING_PRODUCT_NAME,
    COUNT_IF(QUANTITY IS NULL) AS MISSING_QUANTITY,
    COUNT_IF(UNIT_PRICE_INR IS NULL) AS MISSING_UNIT_PRICE,
    COUNT_IF(ORDER_LOCATION IS NULL) AS MISSING_LOCATION,
    COUNT_IF(PAYMENT_METHOD IS NULL) AS MISSING_PAYMENT_METHOD,
    COUNT_IF(SALES_CHANNEL IS NULL) AS MISSING_SALES_CHANNEL

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW;


CREATE OR REPLACE TABLE
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.CUSTOMERS AS

WITH UNIQUE_CUSTOMERS AS (

    SELECT DISTINCT

        COALESCE(
            NULLIF(TRIM(CUSTOMER_NAME), ''),
            'Unknown'
        ) AS CUSTOMER_NAME,

        COALESCE(
            UPPER(NULLIF(TRIM(CUSTOMER_CITY), '')),
            'UNKNOWN'
        ) AS CUSTOMER_CITY,

        COALESCE(
            UPPER(NULLIF(TRIM(CUSTOMER_TYPE), '')),
            'UNKNOWN'
        ) AS CUSTOMER_TYPE

    FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW
)

SELECT
    ROW_NUMBER() OVER (
        ORDER BY CUSTOMER_NAME, CUSTOMER_CITY, CUSTOMER_TYPE
    ) AS CUSTOMER_ID,

    CUSTOMER_NAME,
    CUSTOMER_CITY,
    CUSTOMER_TYPE

FROM UNIQUE_CUSTOMERS;

SELECT *
FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.CUSTOMERS;

SELECT COUNT(*) AS TOTAL_CUSTOMERS
FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.CUSTOMERS;


CREATE OR REPLACE TABLE
    RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES AS

SELECT
    R.ORDER_ID,
    C.CUSTOMER_ID,
    R.ORDER_DATE,
    R.PRODUCT_NAME,
    R.QUANTITY,
    R.UNIT_PRICE_INR,
    R.ORDER_LOCATION,
    R.PAYMENT_METHOD,
    R.SALES_CHANNEL

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW R

LEFT JOIN RENEWABLE_ENERGY_DB.SALES_SCHEMA.CUSTOMERS C

    ON COALESCE(
        NULLIF(TRIM(R.CUSTOMER_NAME), ''),
        'Unknown'
    ) = C.CUSTOMER_NAME

    AND COALESCE(
        UPPER(NULLIF(TRIM(R.CUSTOMER_CITY), '')),
        'UNKNOWN'
    ) = C.CUSTOMER_CITY

    AND COALESCE(
        UPPER(NULLIF(TRIM(R.CUSTOMER_TYPE), '')),
        'UNKNOWN'
    ) = C.CUSTOMER_TYPE;


SELECT *
FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES;


SELECT
    COUNT(*) AS TOTAL_SALES,

    COUNT(CUSTOMER_ID) AS MATCHED_CUSTOMERS,

    COUNT_IF(CUSTOMER_ID IS NULL) AS UNMATCHED_CUSTOMERS

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES;


SELECT *
FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES;

SELECT
    COUNT(*) AS TOTAL_SALES,

    COUNT(CUSTOMER_ID) AS MATCHED_CUSTOMERS,

    COUNT_IF(CUSTOMER_ID IS NULL) AS UNMATCHED_CUSTOMERS

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES;


SELECT
    ORDER_ID,
    ORDER_DATE,
    PRODUCT_NAME,
    QUANTITY,
    UNIT_PRICE_INR,
    ORDER_LOCATION

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES

WHERE UPPER(TRIM(ORDER_LOCATION)) = 'CHENNAI';


SELECT
    COUNT(*) AS TOTAL_ORDERS,

    SUM(QUANTITY) AS TOTAL_UNITS_SOLD,

    SUM(
        QUANTITY * UNIT_PRICE_INR
    ) AS TOTAL_REVENUE_INR

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES;

SELECT
    PRODUCT_NAME,

    SUM(QUANTITY) AS TOTAL_QUANTITY,

    SUM(
        QUANTITY * UNIT_PRICE_INR
    ) AS TOTAL_REVENUE_INR

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES

GROUP BY PRODUCT_NAME

ORDER BY TOTAL_REVENUE_INR DESC;


SELECT
    S.ORDER_ID,
    C.CUSTOMER_NAME,
    C.CUSTOMER_CITY,
    C.CUSTOMER_TYPE,
    S.PRODUCT_NAME,
    S.QUANTITY,
    S.UNIT_PRICE_INR,

    S.QUANTITY * S.UNIT_PRICE_INR
        AS TOTAL_AMOUNT

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES S

INNER JOIN RENEWABLE_ENERGY_DB.SALES_SCHEMA.CUSTOMERS C

    ON S.CUSTOMER_ID = C.CUSTOMER_ID;



    SELECT
    C.CUSTOMER_TYPE,

    COUNT(S.ORDER_ID) AS TOTAL_ORDERS,

    SUM(S.QUANTITY) AS TOTAL_UNITS_SOLD,

    SUM(
        S.QUANTITY * S.UNIT_PRICE_INR
    ) AS TOTAL_REVENUE_INR

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES S

INNER JOIN RENEWABLE_ENERGY_DB.SALES_SCHEMA.CUSTOMERS C

    ON S.CUSTOMER_ID = C.CUSTOMER_ID

GROUP BY C.CUSTOMER_TYPE

ORDER BY TOTAL_REVENUE_INR DESC;


SELECT
    TRIM('') AS EMPTY_STRING,

    TRIM('     ') AS WHITESPACE_STRING,

    TRIM(NULL) AS NULL_VALUE;


    SELECT
    TRIM('') IS NULL AS EMPTY_IS_NULL,

    TRIM('     ') IS NULL AS WHITESPACE_IS_NULL,

    TRIM(NULL) IS NULL AS NULL_IS_NULL;


    SELECT
    CUSTOMER_NAME,

    CUSTOMER_CITY,

    TRIM(CUSTOMER_CITY) AS TRIMMED_CITY,

    TRIM(CUSTOMER_CITY) IS NULL AS CITY_IS_NULL

FROM RENEWABLE_ENERGY_DB.SALES_SCHEMA.SALES_RAW

WHERE CUSTOMER_CITY IS NULL
   OR TRIM(CUSTOMER_CITY) = '';


   SHOW TABLES IN SCHEMA
    RENEWABLE_ENERGY_DB.SALES_SCHEMA;

SHOW STAGES IN SCHEMA
    RENEWABLE_ENERGY_DB.SALES_SCHEMA;

SHOW FILE FORMATS IN SCHEMA
    RENEWABLE_ENERGY_DB.SALES_SCHEMA;

