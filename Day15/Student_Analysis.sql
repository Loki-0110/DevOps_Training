USE ROLE SYSADMIN;

SELECT CURRENT_ROLE();

CREATE DATABASE IF NOT EXISTS STUDENT_PERFORMANCE_DB;

SHOW DATABASES LIKE 'STUDENT_PERFORMANCE_DB';

CREATE SCHEMA IF NOT EXISTS
STUDENT_PERFORMANCE_DB.STUDENT_RAW;

SHOW SCHEMAS IN DATABASE STUDENT_PERFORMANCE_DB;

USE DATABASE STUDENT_PERFORMANCE_DB;

USE SCHEMA STUDENT_RAW;

CREATE WAREHOUSE IF NOT EXISTS STUDENT_PERFORMANCE_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

SHOW WAREHOUSES LIKE 'STUDENT_PERFORMANCE_WH';
DESCRIBE WAREHOUSE STUDENT_PERFORMANCE_WH;

USE WAREHOUSE STUDENT_PERFORMANCE_WH;

CREATE TABLE IF NOT EXISTS
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
(
    STUDENT_ID NUMBER(10,0),
    AGE NUMBER(3,0),
    GENDER VARCHAR(20),
    STUDY_STATUS VARCHAR(30),
    ATTENDANCE_PERCENT NUMBER(5,2),
    PERFORMANCE VARCHAR(30),
    ATTENDANCE_STATUS VARCHAR(30),
    AGE_GROUP VARCHAR(30),
    ATTENDANCE_SCORE_100 NUMBER(5,2),
    ATTENDANCE_RANK NUMBER(10,0)
);

SHOW TABLES IN SCHEMA STUDENT_PERFORMANCE_DB.STUDENT_RAW;

DESCRIBE TABLE
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE;

CREATE FILE FORMAT IF NOT EXISTS
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_CSV_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
EMPTY_FIELD_AS_NULL = TRUE
NULL_IF = ('NULL', 'null');

SHOW FILE FORMATS IN SCHEMA STUDENT_PERFORMANCE_DB.STUDENT_RAW;

DESCRIBE FILE FORMAT
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_CSV_FORMAT;

CREATE STAGE IF NOT EXISTS
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_STAGE
FILE_FORMAT =
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_CSV_FORMAT;

SHOW STAGES IN SCHEMA STUDENT_PERFORMANCE_DB.STUDENT_RAW;

DESCRIBE STAGE
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_STAGE;

LIST @STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_STAGE;

COPY INTO
STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
FROM
@STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_STAGE
FILE_FORMAT = (
    FORMAT_NAME =
    'STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE_CSV_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT COUNT(*) AS TOTAL_RECORDS
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE;


SELECT *
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
ORDER BY STUDENT_ID;

SELECT *
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
ORDER BY STUDENT_ID;


SELECT
    COUNT_IF(STUDENT_ID IS NULL) AS NULL_STUDENT_ID,
    COUNT_IF(AGE IS NULL) AS NULL_AGE,
    COUNT_IF(GENDER IS NULL) AS NULL_GENDER,
    COUNT_IF(STUDY_STATUS IS NULL) AS NULL_STUDY_STATUS,
    COUNT_IF(ATTENDANCE_PERCENT IS NULL) AS NULL_ATTENDANCE_PERCENT,
    COUNT_IF(PERFORMANCE IS NULL) AS NULL_PERFORMANCE,
    COUNT_IF(ATTENDANCE_STATUS IS NULL) AS NULL_ATTENDANCE_STATUS,
    COUNT_IF(AGE_GROUP IS NULL) AS NULL_AGE_GROUP,
    COUNT_IF(ATTENDANCE_SCORE_100 IS NULL) AS NULL_ATTENDANCE_SCORE,
    COUNT_IF(ATTENDANCE_RANK IS NULL) AS NULL_ATTENDANCE_RANK
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE;

SELECT STUDENT_ID, COUNT(*) AS RECORD_COUNT
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
GROUP BY STUDENT_ID
HAVING COUNT(*) > 1;

SELECT
    MIN(ATTENDANCE_PERCENT) AS MIN_ATTENDANCE,
    MAX(ATTENDANCE_PERCENT) AS MAX_ATTENDANCE,
    AVG(ATTENDANCE_PERCENT) AS AVG_ATTENDANCE,
    MIN(ATTENDANCE_SCORE_100) AS MIN_SCORE,
    MAX(ATTENDANCE_SCORE_100) AS MAX_SCORE,
    AVG(ATTENDANCE_SCORE_100) AS AVG_SCORE
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE;

SELECT PERFORMANCE, COUNT(*) AS STUDENT_COUNT
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
GROUP BY PERFORMANCE
ORDER BY STUDENT_COUNT DESC;

SELECT ATTENDANCE_STATUS, COUNT(*) AS STUDENT_COUNT
FROM STUDENT_PERFORMANCE_DB.STUDENT_RAW.STUDENT_PERFORMANCE
GROUP BY ATTENDANCE_STATUS
ORDER BY STUDENT_COUNT DESC;

SHOW DATABASES LIKE 'STUDENT_PERFORMANCE_DB';

SHOW SCHEMAS IN DATABASE STUDENT_PERFORMANCE_DB;

SHOW WAREHOUSES LIKE 'STUDENT_PERFORMANCE_WH';

SHOW TABLES IN SCHEMA STUDENT_PERFORMANCE_DB.STUDENT_RAW;

SHOW FILE FORMATS IN SCHEMA STUDENT_PERFORMANCE_DB.STUDENT_RAW;

SHOW STAGES IN SCHEMA STUDENT_PERFORMANCE_DB.STUDENT_RAW;

SHOW WAREHOUSES LIKE 'STUDENT_PERFORMANCE_WH';

ALTER WAREHOUSE STUDENT_PERFORMANCE_WH SUSPEND;

SHOW WAREHOUSES LIKE 'STUDENT_PERFORMANCE_WH';

DROP DATABASE IF EXISTS STUDENT_PERFORMANCE_DB;

DROP WAREHOUSE IF EXISTS STUDENT_PERFORMANCE_WH;